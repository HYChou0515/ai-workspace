"""docs/plan-job-tool-template.md P8 — the job tool template, through the real
author path.

`sample-tools/job-tool-template/` is handed to whoever runs a job backend, the
way `tool-starter/` is handed to a tool author. It imports nothing from this
package, so nothing here keeps it honest except these: a real build of it (the
builder is the oracle for what the platform accepts), and its three packages'
own tests, which CI does not otherwise run.

Slow (real uv venvs), so integration, like `test_end_to_end.py`.
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

import pytest

_TEMPLATE = Path(__file__).resolve().parents[2] / "sample-tools" / "job-tool-template"

pytestmark = [
    pytest.mark.integration,
    pytest.mark.skipif(shutil.which("uv") is None, reason="uv not on PATH"),
]


def test_the_template_builds_into_an_artifact_the_platform_accepts(tmp_path: Path):
    """The real build: prebuild, pack, and the smoke that runs the bundle's
    own launcher through the three-stage contract."""
    from workspace_app.tooling.builder import BUNDLE_NAME, build_artifact

    # uv caches a built wheel by (name, version), and prebuild refreshes only
    # the tool's own package: without this, an edit to contract/ or
    # example-impl/ at an unchanged version builds the OLD code into the
    # bundle, and this test would be grading a stale copy.
    subprocess.run(["uv", "cache", "clean", "job-contract", "example-jobs"], check=True)
    manifest = build_artifact(source=_TEMPLATE / "template", out=tmp_path, builder_id="test:job")

    assert manifest.name == "job-tool"
    assert [c.name for c in manifest.commands] == [
        "submit", "get", "list", "update", "cancel", "logs", "fetch",
    ]  # fmt: skip
    assert all(c.description.strip() for c in manifest.commands)
    assert (tmp_path / BUNDLE_NAME).is_file()

    # env.json is generated by the template (D19); the builder's own parser
    # read it into the manifest, so this is the template's output judged by
    # the platform's reader rather than by a copy of its rules.
    assert manifest.env is not None, "the template's env.json did not reach the manifest"
    (declared,) = manifest.env
    assert (declared.name, declared.required) == ("DEMO_JOBS_USER", True)
    assert declared.description.strip()


@pytest.mark.parametrize("package", ["contract", "example-impl", "template"])
def test_each_package_of_the_template_passes_its_own_tests(package: str):
    proc = subprocess.run(
        ["uv", "run", "--frozen", "pytest", "-q"],
        cwd=_TEMPLATE / package,
        capture_output=True,
        text=True,
        timeout=600,
    )
    assert proc.returncode == 0, proc.stdout[-3000:] + proc.stderr[-3000:]
